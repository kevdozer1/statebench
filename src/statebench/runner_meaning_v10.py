"""Turn 10 meaning-layer episode loop: runner_meaning_v9 with the truth re-decision kept out of a backend's history
(snapshot/restore). Generated by gen_meaning_v10.py.

Turn 9 docstring: runner_meaning (Turn 8, pinned) plus ``choice_on_truth`` per decision.

Generated by gen_meaning_v9.py. Original docstring follows.

Turn 8 meaning-layer episode loop (no rendering).

Geometry:
* ``exact``: the oracle packet (sim-truth geometry), the stand-in for strong reconstruction.
* ``L1`` / ``L2``: reconstruction-grade geometry, ASSUMPTIONS declared in rules_turn8: the true
  cube position plus a persistent per-episode bias (L1 2 mm, L2 5 mm, random direction per
  seed) plus per-frame Gaussian jitter (L1 1 mm, L2 2 mm per axis), redrawn at every 50 ms
  observation tick; yaw exact. The estimated state is built by ``observation_e1``'s
  declared rules from that estimate (so contact, support and the E1.1 motion relation
  follow from the geometry), and the executor acts on it.

Meaning fields (the labels a consumer depends on): ``contact`` (contact.gripper_target),
``grip`` (gripper_closed_on_object / gripper_closed_empty), ``held``
(relations.target_moving_with_gripper and object_moving_with_gripper),
``released`` (released_at_receptacle), ``at_receptacle`` (object_at_receptacle). Writing a
field writes its base field and every predicate that depends on it, so the packet stays
internally consistent; geometry numbers are never changed by a meaning error.

Truth of each field (logged at every decision; the accuracy reference): contact = a finger
pad touches the cube; grip = commanded closed with a pad touching (on_object), commanded
closed with none (empty), open otherwise; held = the oracle motion relation (true, false or
unknown while the arm is still), and a second reference ``held_bilateral`` = both fingers
touch the cube (the quantity a fingertip sensor measures; accuracy is reported against
both); released and at_receptacle = the v0.4 predicates on the oracle packet.

Sources:
* ``truth``: the truth fields, optionally with one error model (Phase 1).
* ``rules``: v0.4 predicates computed from the (reconstruction-grade) state.
* ``instrumented``: a declared simulated fingertip sensor supplies contact, grip and held
  (``SENSOR``); released and at_receptacle come from the geometry rules.
* ``spec``: the truth fields degraded, all at once, to the Phase 1 spec boundary (``spec``
  argument: per field, a list of (error type, level)).

Error models (per field; one uniform draw per decision per field from a per-episode RNG,
the same draws at every level, so levels are coupled): ``delay`` (the truth value at
t - d, 50 ms buffer), ``flicker`` (flip with p), ``fpr`` (a negative reported positive with
p), ``fnr`` (a positive reported negative with p), ``abstain`` (unknown with p). ``unknown``
truth values are never flipped; grip errors apply only while the gripper is commanded
closed.

The loop is runner_v7's (loop exit and loop stop on, forced miss on perturbed seeds).
Corrections for counterfactual labels: ``pose`` (exact geometry) and ``meaning:<field>``
(truth for that field).
"""

from __future__ import annotations

import copy
import time
from typing import Any

import numpy as np

from . import rules as prereg1
from .backends.base import NEXT_ACTION, default_questions
from .env_v8 import EnvV8
from .executor_v6 import ExecutorV6
from .observation_e1 import build_estimated_state, estimated_events
from .observation_e1_1 import lift_diverged_interp, moving_interp
from .observations import HistoryBuffer, build_compact_truth, build_proprio
from .perception_e1 import CONSTANTS
from .predicates_v4 import build_predicates_v4
from .reference_v8 import heights
from .representations_v2 import CONDITIONS_V2_BY_NAME, prepare_v2, render
from .runner_v2 import completion_labels
from .runner_v6 import LOOP_REPEATS, LOOP_TCP_M, MISS_OFFSET
from .scene import perturbation_fires
from .scene_v8 import VARIANTS
from .verify import RUNNING, SUCCESS, Verifier

RUNNER_VERSION = "statebench-runner-meaning/v10"
FIELDS = ("contact", "grip", "held", "released", "at_receptacle")
ERROR_TYPES = ("delay", "flicker", "fpr", "fnr", "abstain")
GEOMETRY = {"exact": (0.0, 0.0), "L1": (0.002, 0.001), "L2": (0.005, 0.002)}
TICK_S = 0.05
LOOP_STOP_REPEATS = 6
SENSOR = {"rate_hz": 100.0, "force_noise_sd_n": 0.10, "contact_threshold_n": 0.5, "held_threshold_n": 2.0,
          "declaration": ("instrumented capture: a fingertip normal-force sensor on each finger pad, sampled at "
                          "100 Hz with Gaussian noise (sd 0.10 N); contact = either pad above 0.5 N; held = both "
                          "pads above 2.0 N; grip on_object = commanded closed and held, empty = commanded "
                          "closed and no contact, unknown otherwise; object_moving_with_gripper = held")}
POSITIVE = {"contact": "contact", "grip": "on_object", "held": True, "released": True, "at_receptacle": True}
NEGATIVE = {"contact": "no_contact", "grip": "empty", "held": False, "released": False, "at_receptacle": False}


def _flip(field: str, v):
    if v == POSITIVE[field]:
        return NEGATIVE[field]
    if v == NEGATIVE[field]:
        return POSITIVE[field]
    return v


def apply_error(field: str, v, kind: str, level: float, u: float, delayed=None):
    if field == "grip" and v == "open":
        return v
    if kind == "delay":
        return delayed
    if kind == "flicker":
        return _flip(field, v) if u < level else v
    if kind == "fpr":
        return POSITIVE[field] if (v == NEGATIVE[field] and u < level) else v
    if kind == "fnr":
        return NEGATIVE[field] if (v == POSITIVE[field] and u < level) else v
    if kind == "abstain":
        return "unknown" if u < level else v
    raise ValueError(kind)


def read_fields(state: dict, preds: dict) -> dict:
    on, empty = preds.get("gripper_closed_on_object"), preds.get("gripper_closed_empty")
    grip = "unknown" if "unknown" in (on, empty) else ("on_object" if on else ("empty" if empty else "open"))
    return {"contact": (state.get("contact") or {}).get("gripper_target", "unknown"), "grip": grip,
            "held": (state.get("relations") or {}).get("target_moving_with_gripper", "unknown"),
            "released": preds.get("released_at_receptacle"), "at_receptacle": preds.get("object_at_receptacle")}


def write_fields(state: dict, preds: dict, m: dict, command_closed: bool) -> None:
    if "contact" in m:
        state.setdefault("contact", {})["gripper_target"] = m["contact"]
    if "grip" in m:
        g = m["grip"]
        if g == "unknown":
            preds["gripper_closed_on_object"] = preds["gripper_closed_empty"] = "unknown"
        elif g == "open" or not command_closed:
            preds["gripper_closed_on_object"] = preds["gripper_closed_empty"] = False
        else:
            preds["gripper_closed_on_object"] = g == "on_object"
            preds["gripper_closed_empty"] = g == "empty"
    if "held" in m:
        state.setdefault("relations", {})["target_moving_with_gripper"] = m["held"]
        preds["object_moving_with_gripper"] = m["held"]
    if "released" in m:
        preds["released_at_receptacle"] = m["released"]
    if "at_receptacle" in m:
        preds["object_at_receptacle"] = m["at_receptacle"]


def run_episode_meaning(seed: int, consumer: str, backend, *, variant: str = "V0", geometry: str = "exact",
                        source: str = "truth", error: tuple | None = None, spec: dict | None = None,
                        corrections: tuple[str, ...] = (), max_steps: int = prereg1.MAX_DECISION_STEPS) -> dict:
    started = time.perf_counter()
    env = EnvV8(seed, variant=variant)
    events: list[dict] = []
    diverged: list[dict] = []
    verifier = Verifier(env)
    cfg = VARIANTS[variant]
    constants = dict(CONSTANTS, cube_edge_m=2 * cfg.cube_half)
    grasp_z, place_z = heights(variant)
    pconst = {"grasp_offset_m": round(grasp_z - cfg.cube_half, 4), "object_size_m": 2 * cfg.cube_half}
    geom = "exact" if "pose" in corrections else geometry
    bias_m, jitter_m = GEOMETRY[geom]
    grng = np.random.default_rng(5_000_011 + seed)
    d = grng.normal(size=3)
    bias = bias_m * d / np.linalg.norm(d)
    erng = np.random.default_rng(9_000_013 + seed)
    srng = np.random.default_rng(6_000_007 + seed)
    history, est_history = HistoryBuffer(), HistoryBuffer()
    track: list[dict] = []
    buffer: list[tuple[float, dict]] = []  # truth meaning at 50 ms ticks, for delay
    sensor = {"t": -1.0, "left": 0.0, "right": 0.0}
    tick = {"next": 0.0}

    def truth_fields() -> dict:
        fingers = env.truth_cube_contacts()["fingers"]
        closed = env.proprio_grip_command() == "closed"
        compact = build_compact_truth(env, events)
        preds = build_predicates_v4(compact, build_proprio(env), [s for _, s in history.snapshots()],
                                    pconst)["values"]
        return {"contact": "contact" if fingers else "no_contact",
                "grip": ("on_object" if fingers else "empty") if closed else "open",
                "held": compact["relations"]["target_moving_with_gripper"],
                "released": preds["released_at_receptacle"], "at_receptacle": preds["object_at_receptacle"],
                "held_bilateral": len(fingers) >= 2}

    def noisy_cube():
        return np.asarray(env.truth_cube_position(), dtype=float) + bias + grng.normal(0.0, jitter_m, size=3)

    def hook(env_):
        if env_.t + 1e-9 >= sensor["t"] + 1.0 / SENSOR["rate_hz"]:
            f = env_.pad_normal_forces()
            sensor.update(t=env_.t, left=f["left"] + srng.normal(0, SENSOR["force_noise_sd_n"]),
                          right=f["right"] + srng.normal(0, SENSOR["force_noise_sd_n"]))
        if env_.t + 1e-9 >= tick["next"]:
            tick["next"] = env_.t + TICK_S
            history.push(env_.t, build_compact_truth(env_, events))
            buffer.append((env_.t, truth_fields()))
            del buffer[:-40]
            if geom != "exact":
                track.append({"t": round(env_.t, 3), "cube_m": noisy_cube().tolist(),
                              "tcp_m": [float(v) for v in env_.proprio_tcp()]})
                del track[:-60]

    env.step_hooks += [verifier.update, hook]
    hook(env)
    fired = perturbation_fires(seed, prereg1.PERTURBATION_PROBABILITY)
    offset = np.array([0.0, 0.0, MISS_OFFSET.get(variant, 0.035)]) if fired else None
    executor = ExecutorV6(env, events, offset, grasp_z, place_z)
    rng = np.random.default_rng(seed + 40_000)
    questions = default_questions()
    rcond = CONDITIONS_V2_BY_NAME["R4j"]
    steps, loop_exits, recent, loop_run = [], [], [], []
    loop_stopped = False
    for index in range(max_steps):
        if verifier.status != RUNNING:
            break
        proprio = build_proprio(env)
        closed = proprio["gripper_command"] == "closed"
        compact = build_compact_truth(env, events)
        history.push(env.t, compact)
        if geom == "exact":
            base = compact
            hist = history
        else:
            est = {"cube_m": noisy_cube().tolist(), "yaw_mod90_rad": float(env.truth_cube_yaw()) % (np.pi / 2),
                   "t_est": env.t, "fresh": True, "visible_fraction": 1.0}
            base = build_estimated_state(est, proprio, proprio, estimated_events(events, diverged), track, constants)
            if track:
                base["relations"]["target_moving_with_gripper"] = moving_interp(track, track[-1]["t"])
            est_history.push(env.t, base)
            hist = est_history
        state, h, _ = prepare_v2(rcond, base, hist, env.t, rng, proprio=proprio)
        block = build_predicates_v4(state, proprio, h, pconst)
        preds = block["values"]
        truth = truth_fields()
        # the meaning source
        if source == "truth":
            write_fields(state, preds, truth, closed)
        elif source == "instrumented":
            contact = max(sensor["left"], sensor["right"]) > SENSOR["contact_threshold_n"]
            held = min(sensor["left"], sensor["right"]) > SENSOR["held_threshold_n"]
            grip = ("on_object" if held else ("empty" if not contact else "unknown")) if closed else "open"
            write_fields(state, preds, {"contact": "contact" if contact else "no_contact", "grip": grip,
                                        "held": bool(held)}, closed)
        elif source == "spec":
            write_fields(state, preds, truth, closed)
        u = {f: float(erng.uniform()) for f in FIELDS}
        errs = [error] if error else []
        if source == "spec":
            errs = [(f, k, lv) for f, lst in (spec or {}).items() for k, lv in lst]
        cur = read_fields(state, preds)
        for f, kind, level in errs:
            delayed = None
            if kind == "delay":
                past = [m for t_, m in buffer if t_ <= env.t - level + 1e-9]
                delayed = (past[-1] if past else buffer[0][1])[f]
            cur[f] = apply_error(f, cur[f], kind, level, u[f], delayed)
            if kind in ("fpr", "fnr", "flicker", "abstain"):
                u[f] = float(erng.uniform())  # a fresh draw for the next error type on the same field
        for corr in corrections:
            if corr.startswith("meaning:"):
                cur[corr.split(":", 1)[1]] = truth[corr.split(":", 1)[1]]
        write_fields(state, preds, cur, closed)
        state["predicates"] = block
        text = render(rcond, state)
        decision = backend.decide(text, questions, instruction_override=None)
        chosen = decision.answers[NEXT_ACTION].choice if NEXT_ACTION in decision.answers else "inspect"
        tstate = copy.deepcopy(state)
        write_fields(tstate, tstate["predicates"]["values"], truth, closed)
        snap = backend.snapshot() if hasattr(backend, "snapshot") else None
        tdec = backend.decide(render(rcond, tstate), questions, instruction_override=None)
        if snap is not None:
            backend.restore(snap)
        choice_on_truth = tdec.answers[NEXT_ACTION].choice if NEXT_ACTION in tdec.answers else "inspect"
        primitive = chosen
        tcp_now = np.asarray(proprio["tcp_position_m"])
        recent.append((chosen, tuple(sorted((k, str(v)) for k, v in preds.items())), tcp_now))
        recent = recent[-LOOP_REPEATS:]
        exit_here = None
        if (len(recent) == LOOP_REPEATS and chosen != "approach" and len({r[0] for r in recent}) == 1
                and len({r[1] for r in recent}) == 1
                and max(float(np.linalg.norm(r[2] - recent[0][2])) for r in recent) < LOOP_TCP_M):
            primitive = "approach"
            exit_here = {"index": index, "repeated": chosen}
            loop_exits.append(exit_here)
            recent = []
        t0 = env.t
        executor.execute(primitive, state, h)
        if primitive == "test_lift" and geom != "exact":
            if lift_diverged_interp(track, t0, env.t):
                diverged.append({"t": round(env.t, 3), "event": "target_motion_diverged"})
        after = completion_labels(verifier)
        steps.append({"index": index, "t": round(t0, 3), "chosen": chosen, "choice_on_truth": choice_on_truth,
                      "loop_exit": exit_here,
                      "delivered": {f: read_fields(state, preds)[f] for f in FIELDS}, "truth": truth,
                      "verifier_after": {"status": verifier.status, "conditions": after["conditions"]}})
        loop_run.append((primitive, tuple(sorted(after["conditions"].items()))))
        loop_run = loop_run[-LOOP_STOP_REPEATS:]
        if len(loop_run) == LOOP_STOP_REPEATS and len(set(loop_run)) == 1:
            verifier.finish("loop: the same primitive 6 times with no change in the verifier conditions")
            loop_stopped = True
            break
        if verifier.status != RUNNING:
            break
    if verifier.status == RUNNING:
        verifier.finish("decision loop ended without a verified placement")
    report = verifier.report()
    env.close()
    success = report["status"] == SUCCESS
    return {"seed": seed, "consumer": consumer, "variant": variant, "geometry": geometry, "source": source,
            "error": list(error) if error else None, "spec": spec, "corrections": list(corrections),
            "runner_version": RUNNER_VERSION, "success": success, "verifier": report,
            "time_to_success_s": report["t_success"] if success else None, "loop_stopped": loop_stopped,
            "failure_cause": "loop" if loop_stopped else None, "perturbation_fired": fired,
            "decision_steps": len(steps), "loop_exits": loop_exits, "excluded": False, "backend_errors": 0,
            "latencies": [], "wall_seconds": round(time.perf_counter() - started, 3), "steps": steps}
